-- Ejecutar SOLO en base de laboratorio validada. No se ejecuta automaticamente.
-- Registro administrativo separado del saldo authoritative del legacy.
CREATE TABLE IF NOT EXISTS cuentas_gestion (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 titular VARCHAR(100) NOT NULL,
 tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('AHORRO','CORRIENTE')),
 estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVA' CHECK (estado IN ('ACTIVA','CERRADA')),
 saldo_inicial NUMERIC(18,2) NOT NULL CHECK (saldo_inicial >= 0),
 creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
