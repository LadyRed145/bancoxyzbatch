CREATE TABLE IF NOT EXISTS pagos_saldos (
 cuenta_id BIGINT PRIMARY KEY,
 saldo_actual NUMERIC(18,2) NOT NULL CHECK (saldo_actual >= 0),
 actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS pagos_movimientos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 solicitud_id UUID NOT NULL REFERENCES pagos_solicitudes(id),
 cuenta_id BIGINT NOT NULL REFERENCES pagos_saldos(cuenta_id),
 sentido VARCHAR(8) NOT NULL CHECK (sentido IN ('DEBITO','CREDITO')),
 monto NUMERIC(18,2) NOT NULL CHECK (monto > 0),
 creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 CONSTRAINT pagos_movimientos_no_duplicado UNIQUE(solicitud_id,cuenta_id,sentido)
);
CREATE INDEX IF NOT EXISTS ix_pagos_movimientos_cuenta ON pagos_movimientos(cuenta_id,creado_en);
